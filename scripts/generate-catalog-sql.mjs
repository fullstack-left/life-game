#!/usr/bin/env node
/**
 * Prints the SQL seed for public.catalog_items from the shared TS catalog.
 *   node --experimental-strip-types scripts/generate-catalog-sql.mjs > supabase/migrations/<ts>_catalog_seed.sql
 * A unit test (catalogSync.test.ts) fails CI if the committed seed drifts from catalog.ts.
 */
const { CATALOG, FOODS } = await import('../supabase/functions/_shared/pure/catalog.ts');

const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
const rows = [
  ...CATALOG.map((i) => `  (${q(i.id)}, ${q(i.slot)}, 'item', ${i.price}, ${i.starter === true})`),
  ...FOODS.map((f) => `  (${q(f.id)}, 'food', 'food', ${f.price}, false)`),
];
console.log(`-- AUTO-GENERATED by scripts/generate-catalog-sql.mjs from supabase/functions/_shared/pure/catalog.ts
-- Authoritative prices. Re-run the generator after editing the catalog.

insert into public.catalog_items (id, slot, kind, price, starter) values
${rows.join(',\n')}
on conflict (id) do update
  set slot = excluded.slot, kind = excluded.kind, price = excluded.price, starter = excluded.starter, active = true;
`);
