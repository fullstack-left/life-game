#!/usr/bin/env node
/**
 * Generates `src/core/crypto/secret.generated.ts` — the obfuscated client HMAC key.
 *
 *   LIFEGAME_CLIENT_HMAC_SECRET=... node scripts/generate-client-secret.mjs
 *
 * The secret is XOR-masked with a random pad, split into shuffled chunks and
 * reassembled at runtime, so it never appears as a contiguous string in the
 * Hermes bytecode. This raises the cost of casual extraction (strings/grep on
 * the APK) — it is NOT a substitute for server-side validation. The server
 * treats the signature as one signal among several (session nonce, duration
 * window, theoretical-max score, rate limiting).
 *
 * Release pipelines run this with the production secret from CI secrets; the
 * committed file contains the local development key only.
 */
import { randomBytes } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const DEV_SECRET = 'local-dev-hmac-secret-change-me-0123456789';
const secret = process.env.LIFEGAME_CLIENT_HMAC_SECRET ?? DEV_SECRET;
if (secret.length < 32) {
  console.error('LIFEGAME_CLIENT_HMAC_SECRET must be at least 32 characters');
  process.exit(1);
}

const plain = Buffer.from(secret, 'utf8');
const mask = randomBytes(plain.length);
const masked = plain.map((b, i) => b ^ mask[i]);

const CHUNK = 7;
const chunks = [];
for (let i = 0; i < masked.length; i += CHUNK) {
  chunks.push({ order: chunks.length, bytes: Array.from(masked.subarray(i, i + CHUNK)) });
}
// Fisher–Yates shuffle so chunk order in the bundle is meaningless.
for (let i = chunks.length - 1; i > 0; i--) {
  const j = randomBytes(1)[0] % (i + 1);
  [chunks[i], chunks[j]] = [chunks[j], chunks[i]];
}

const out = `/* eslint-disable */
// AUTO-GENERATED by scripts/generate-client-secret.mjs — do not edit by hand.
// ${process.env.LIFEGAME_CLIENT_HMAC_SECRET ? 'Release build key.' : 'Local development key (matches supabase/functions/.env.example).'}
export const P: ReadonlyArray<readonly [number, readonly number[]]> = ${JSON.stringify(
  chunks.map((c) => [c.order, c.bytes]),
)};
export const K: readonly number[] = ${JSON.stringify(Array.from(mask))};
`;

const target = resolve(dirname(fileURLToPath(import.meta.url)), '../src/core/crypto/secret.generated.ts');
writeFileSync(target, out);
console.log(`Wrote ${target} (${plain.length} bytes, ${chunks.length} chunks)`);
